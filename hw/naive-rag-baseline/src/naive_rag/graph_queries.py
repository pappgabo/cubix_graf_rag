"""Run the queries in `graph/cypher/queries.cypher` and write the output.

The queries live in a .cypher file rather than in Python so they can be
pasted straight into Neo4j Browser; this module only parses the header
comments, binds the parameters and renders the result as Markdown tables
(`graph/query-results.md`), so the report cannot drift from what actually ran.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from .config import get_settings
from .graph import query

_HEADER = re.compile(r"^//\s*===\s*(?P<id>\S+)\s*\|\s*(?P<title>.+?)\s*===\s*$")
_PARAM = re.compile(r"^//\s*@param\s+(?P<name>\w+)\s*=\s*(?P<value>.*?)\s*$")
_COMMENT = re.compile(r"^//\s?(?P<text>.*)$")


@dataclass
class GraphQuery:
    id: str
    title: str
    description: str
    cypher: str
    params: dict[str, Any] = field(default_factory=dict)


def _finish(cypher_lines: list[str]) -> str:
    return "\n".join(cypher_lines).strip().rstrip(";").strip()


def _typed(value: str) -> Any:
    """`@param last_year = 2032` has to reach Cypher as a number, not '2032'."""
    for cast in (int, float):
        try:
            return cast(value)
        except ValueError:
            continue
    return value


def parse_queries(path: Path) -> list[GraphQuery]:
    queries: list[GraphQuery] = []
    cur: GraphQuery | None = None
    body: list[str] = []
    notes: list[str] = []

    for line in path.read_text(encoding="utf-8").splitlines():
        header = _HEADER.match(line)
        if header:
            if cur:
                cur.cypher = _finish(body)
                queries.append(cur)
            cur = GraphQuery(id=header["id"], title=header["title"],
                             description="", cypher="")
            body, notes = [], []
            continue
        if cur is None:
            continue  # file preamble
        param = _PARAM.match(line)
        if param:
            cur.params[param["name"]] = _typed(param["value"])
            continue
        comment = _COMMENT.match(line)
        if comment and not body:
            # Comments before the statement are the description; comments
            # inside it belong to the Cypher and are kept verbatim.
            if comment["text"].strip():
                notes.append(comment["text"].strip())
            cur.description = " ".join(notes)
            continue
        if line.strip() or body:
            body.append(line)

    if cur:
        cur.cypher = _finish(body)
        queries.append(cur)
    return queries


def _cell(value: Any) -> str:
    if value is None:
        return "—"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, list):
        return ", ".join(_cell(v) for v in value) if value else "—"
    return str(value).replace("|", "\\|").replace("\n", " ")


def render_table(rows: list[dict]) -> str:
    if not rows:
        return "_(no rows — which is the expected answer here)_"
    cols = list(rows[0])
    head = "| " + " | ".join(cols) + " |"
    rule = "|" + "|".join("---" for _ in cols) + "|"
    body = ["| " + " | ".join(_cell(r.get(c)) for c in cols) + " |"
            for r in rows]
    return "\n".join([head, rule, *body])


def run_queries(only: str | None = None) -> list[dict]:
    """Execute the query file; returns one record per query."""
    s = get_settings()
    path = s.graph_dir / "cypher" / "queries.cypher"
    queries = parse_queries(path)
    if only:
        queries = [q for q in queries if q.id.lower() == only.lower()]
        if not queries:
            raise SystemExit(f"error: no query with id '{only}' in {path.name}")

    out = []
    for q in queries:
        # The corpus name belongs to the configuration, not to the query file.
        params = dict(q.params)
        if "corpus" in params:
            params["corpus"] = s.corpus_name
        rows = query(q.cypher, **params)
        out.append({"id": q.id, "title": q.title, "description": q.description,
                    "cypher": q.cypher, "params": params, "rows": rows})
    return out


def write_report(results: list[dict]) -> Path:
    s = get_settings()
    info = query(
        "MATCH (c:Corpus {name: $name}) "
        "RETURN c.chunk_size AS chunk_size, c.chunk_overlap AS chunk_overlap, "
        "c.run_id AS run_id", name=s.corpus_name)
    meta = info[0] if info else {}

    lines = [
        "# Cypher queries and their output",
        "",
        "Generated by `uv run naive-rag graph query` — do not edit by hand.",
        "The statements live in [`cypher/queries.cypher`](cypher/queries.cypher).",
        "",
        f"- run: `{datetime.now(timezone.utc).isoformat(timespec='seconds')}`",
        (f"- corpus: `{s.corpus_name}`"
         f" (document-graph load `{meta.get('run_id', 'n/a')}`,"
         f" chunk size {meta.get('chunk_size', 'n/a')} /"
         f" overlap {meta.get('chunk_overlap', 'n/a')})"),
        f"- Neo4j: `{s.neo4j_uri}`, database `{s.neo4j_database}`",
        "",
    ]
    for r in results:
        lines += [f"## {r['id']} — {r['title']}", "", r["description"], ""]
        if r["params"]:
            params = ", ".join(f"`${k}` = `{v}`"
                               for k, v in r["params"].items())
            lines += [f"Parameters: {params}", ""]
        lines += ["```cypher", r["cypher"], "```", "",
                  render_table(r["rows"]), ""]

    s.graph_dir.mkdir(parents=True, exist_ok=True)
    out = s.graph_dir / "query-results.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    return out
